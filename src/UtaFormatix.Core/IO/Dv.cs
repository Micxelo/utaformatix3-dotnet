public static class Dv
{
    private const double NoteKeySum = 115.5;
    private const int StartingMeasurePosition = -3;
    private const int FixedMeasurePrefix = 4;
    private const int DefaultVolume = 30;
    private const int MinSegmentLength = 480 * 4;

    public static double ConvertNoteKey(double key) => NoteKeySum - key;

    private static int ConvertNoteKeyInt(int key) => (int)NoteKeySum - key;

    public static Project Parse(string filePath, ImportParams? importParams = null)
    {
        var projectName = Path.GetFileNameWithoutExtension(filePath);
        var fileBytes = File.ReadAllBytes(filePath);
        using var stream = new MemoryStream(fileBytes);
        using var reader = new BinaryReader(stream, Encoding.UTF8, leaveOpen: true);
        var warnings = new List<ImportWarning>();

        reader.BaseStream.Seek(48, SeekOrigin.Begin);

        var tempoCount = reader.ReadInt32();
        var tempos = new List<Tempo>();
        for (var i = 0; i < tempoCount; i++)
        {
            var tickPosition = (long)reader.ReadInt32();
            var bpm = reader.ReadInt32() / 100.0;
            tempos.Add(new Tempo(tickPosition, bpm));
        }

        reader.ReadInt32();
        var timeSignatureCount = reader.ReadInt32();
        var timeSignatures = new List<TimeSignature>();
        for (var i = 0; i < timeSignatureCount; i++)
        {
            var measurePosition = reader.ReadInt32();
            var numerator = reader.ReadInt32();
            var denominator = reader.ReadInt32();
            timeSignatures.Add(new TimeSignature(measurePosition, numerator, denominator));
        }

        var tickPrefix = GetTickPrefix(timeSignatures);
        tempos = CleanupTempos(tempos, tickPrefix, warnings);
        timeSignatures = CleanupTimeSignatures(timeSignatures, warnings);

        var trackCount = reader.ReadInt32();
        var tracks = new List<Track>();
        for (var i = 0; i < trackCount; i++)
        {
            var track = ParseTrack(tickPrefix, tempos, importParams ?? new ImportParams(), reader);
            if (track is not null)
                tracks.Add(track.ValidateNotes());
        }

        tracks = tracks.Select((t, idx) => t with { Id = idx }).ToList();

        return new Project(
            Format: Format.Dv,
            Name: projectName,
            Tracks: tracks,
            TimeSignatures: timeSignatures,
            Tempos: tempos,
            MeasurePrefix: FixedMeasurePrefix,
            ImportWarnings: warnings);
    }

    private static Track? ParseTrack(long tickPrefix, List<Tempo> tempos, ImportParams importParams, BinaryReader reader)
    {
        var trackType = reader.ReadInt32();
        if (trackType != 0)
        {
            SkipRestOfInstTrack(reader);
            return null;
        }

        var trackName = ReadString(reader);
        reader.BaseStream.Seek(14, SeekOrigin.Current);

        var notesWithPitch = new List<DvNoteWithPitch>();
        var segmentPitchDataList = new List<DvSegmentPitchRawData>();
        var segmentCount = reader.ReadInt32();

        for (var s = 0; s < segmentCount; s++)
        {
            var segmentStart = reader.ReadInt32();
            reader.ReadInt32();
            ReadString(reader);
            ReadString(reader);
            reader.BaseStream.Seek(4, SeekOrigin.Current);

            var noteCount = reader.ReadInt32();
            for (var n = 0; n < noteCount; n++)
            {
                var noteStart = reader.ReadInt32();
                var noteLength = reader.ReadInt32();
                var noteKey = ConvertNoteKeyInt(reader.ReadInt32());
                reader.BaseStream.Seek(4, SeekOrigin.Current);
                var lyric = ReadString(reader);
                ReadString(reader);
                reader.BaseStream.Seek(1, SeekOrigin.Current);

                var vibratoData = ParseNoteVibratoData(reader);
                ReadBytes(reader);
                reader.BaseStream.Seek(18, SeekOrigin.Current);

                var benDep = reader.ReadInt32();
                var benLen = reader.ReadInt32();
                var porTail = reader.ReadInt32();
                var porHead = reader.ReadInt32();
                reader.ReadInt32();
                ReadBytes(reader);
                reader.ReadInt32();

                var note = new Note(
                    Id: 0,
                    Key: noteKey,
                    Lyric: lyric,
                    TickOn: (long)segmentStart + noteStart - tickPrefix,
                    TickOff: (long)segmentStart + noteStart - tickPrefix + noteLength);

                notesWithPitch.Add(new DvNoteWithPitch(note, benDep, benLen, porHead, porTail, vibratoData));
            }

            ReadBytes(reader);

            if (importParams.SimpleImport)
            {
                SkipPitchData(reader);
            }
            else
            {
                segmentPitchDataList.Add(ParsePitchData((int)(segmentStart - tickPrefix), reader));
            }

            SkipRestOfSegment(reader);
        }

        var notesValidated = notesWithPitch.ValidateNotes();
        PitchModel? pitch = importParams.SimpleImport
            ? null
            : DeepVocalPitchConversion.PitchFromDvTrack(segmentPitchDataList, notesValidated, tempos);

        return new Track(0, trackName, notesValidated.Select(n => n.Note).ToList(), pitch);
    }

    private static List<(int Ms, int MinusCent)> ParseNoteVibratoData(BinaryReader reader)
    {
        reader.ReadInt32();
        ReadBytes(reader);
        ReadBytes(reader);
        reader.ReadInt32();
        var pointLength = reader.ReadInt32();
        var data = new List<(int, int)>();
        for (var i = 0; i < pointLength; i++)
            data.Add((reader.ReadInt32(), reader.ReadInt32()));
        return data;
    }

    private static DvSegmentPitchRawData ParsePitchData(int tickOffset, BinaryReader reader)
    {
        reader.ReadInt32();
        var pointLength = reader.ReadInt32();
        var data = new List<(int, int)>();
        for (var i = 0; i < pointLength; i++)
            data.Add((reader.ReadInt32(), reader.ReadInt32()));
        return new DvSegmentPitchRawData(tickOffset, data);
    }

    private static void SkipPitchData(BinaryReader reader) => ReadBytes(reader);

    private static void SkipRestOfInstTrack(BinaryReader reader)
    {
        ReadBytes(reader);
        reader.BaseStream.Seek(14, SeekOrigin.Current);
        if (reader.ReadInt32() > 0)
        {
            reader.BaseStream.Seek(8, SeekOrigin.Current);
            ReadBytes(reader);
            ReadBytes(reader);
        }
    }

    private static void SkipRestOfSegment(BinaryReader reader)
    {
        for (var i = 0; i < 5; i++)
            ReadBytes(reader);
    }

    private static long GetTickPrefix(List<TimeSignature> timeSignatures)
    {
        var counter = new TickCounter();
        foreach (var ts in timeSignatures)
        {
            var adjusted = ts with { MeasurePosition = ts.MeasurePosition - StartingMeasurePosition };
            if (adjusted.MeasurePosition < FixedMeasurePrefix)
                counter.GoToMeasure(adjusted);
        }
        counter.GoToMeasure(FixedMeasurePrefix);
        return counter.Tick;
    }

    private static List<Tempo> CleanupTempos(List<Tempo> tempos, long tickPrefix, List<ImportWarning> warnings)
    {
        var results = tempos.Select(t => t with { TickPosition = t.TickPosition - tickPrefix }).ToList();
        var firstTempoIndex = results.FindLastIndex(t => t.TickPosition <= 0);
        for (var i = 0; i < firstTempoIndex; i++)
        {
            warnings.Add(new ImportWarning.TempoIgnoredInPreMeasure(results[0]));
            results.RemoveAt(0);
        }
        if (results.Count > 0)
            results[0] = results[0] with { TickPosition = 0 };
        return results;
    }

    private static List<TimeSignature> CleanupTimeSignatures(List<TimeSignature> timeSignatures, List<ImportWarning> warnings)
    {
        var results = timeSignatures
            .Select(ts => ts with { MeasurePosition = ts.MeasurePosition - StartingMeasurePosition - FixedMeasurePrefix })
            .ToList();
        var firstTsIndex = results.FindLastIndex(ts => ts.MeasurePosition <= 0);
        for (var i = 0; i < firstTsIndex; i++)
        {
            warnings.Add(new ImportWarning.TimeSignatureIgnoredInPreMeasure(results[0]));
            results.RemoveAt(0);
        }
        if (results.Count > 0)
            results[0] = results[0] with { MeasurePosition = 0 };
        return results;
    }

    private static string ReadString(BinaryReader reader)
    {
        var length = reader.ReadInt32();
        var bytes = reader.ReadBytes(length);
        return Encoding.UTF8.GetString(bytes);
    }

    private static byte[] ReadBytes(BinaryReader reader)
    {
        var length = reader.ReadInt32();
        return reader.ReadBytes(length);
    }

    public static void GenerateFile(Project project, string filePath, IEnumerable<FeatureConfig>? features = null)
    {
        var featureList = features?.ToList() ?? [];
        var contentBytes = GenerateContent(project, featureList);
        File.WriteAllBytes(filePath, contentBytes);
    }

    private static byte[] GenerateContent(Project project, List<FeatureConfig> features)
    {
        var bytes = new List<byte>();
        bytes.AddRange(Header);

        var tickPrefix = (long)Constants.TicksInFullNote * project.TimeSignatures[0].Numerator / project.TimeSignatures[0].Denominator * FixedMeasurePrefix;

        var mainBlock = new List<byte>();
        mainBlock.AddRange(Encoding.UTF8.GetBytes("ext1ext2ext3ext4ext5ext6ext7"));
        AddListBlock(mainBlock, GenerateTempos(project.Tempos, tickPrefix));
        AddListBlock(mainBlock, GenerateTimeSignatures(project.TimeSignatures));
        AddList(mainBlock, project.Tracks.Select(t => GenerateTrack(t, tickPrefix, features)).ToList());

        AddBlock(bytes, mainBlock);
        return bytes.ToArray();
    }

    private static List<List<byte>> GenerateTempos(List<Tempo> tempos, long tickPrefix)
    {
        var firstTempo = tempos[0] with { TickPosition = 0 };
        var restOfTempos = tempos.Skip(1).Select(t => t with { TickPosition = t.TickPosition + tickPrefix }).ToList();
        var allTempos = new List<Tempo> { firstTempo };
        allTempos.AddRange(restOfTempos);

        return allTempos.Select(t =>
        {
            var entry = new List<byte>();
            AddInt(entry, (int)t.TickPosition);
            AddInt(entry, (int)(t.Bpm * 100));
            return entry;
        }).ToList();
    }

    private static List<List<byte>> GenerateTimeSignatures(List<TimeSignature> timeSignatures)
    {
        var firstTs = timeSignatures[0] with { MeasurePosition = StartingMeasurePosition };
        var restOfTs = timeSignatures.Skip(1)
            .Select(ts => ts with { MeasurePosition = ts.MeasurePosition + FixedMeasurePrefix + StartingMeasurePosition })
            .ToList();
        var allTs = new List<TimeSignature> { firstTs };
        allTs.AddRange(restOfTs);

        return allTs.Select(ts =>
        {
            var entry = new List<byte>();
            AddInt(entry, ts.MeasurePosition);
            AddInt(entry, ts.Numerator);
            AddInt(entry, ts.Denominator);
            return entry;
        }).ToList();
    }

    private static List<byte> GenerateTrack(Track track, long tickPrefix, List<FeatureConfig> features)
    {
        var segmentBytes = new List<byte>();
        AddInt(segmentBytes, (int)tickPrefix);
        var lastNoteTickOff = track.Notes.Count > 0 ? (int)track.Notes[^1].TickOff : 0;
        AddInt(segmentBytes, Math.Max(lastNoteTickOff, MinSegmentLength));
        AddString(segmentBytes, track.Name);
        AddString(segmentBytes, "");
        AddListBlock(segmentBytes, track.Notes.Select(n => GenerateNote(n, features)).ToList());
        segmentBytes.AddRange(SegmentDefaultParameterData1);

        if (features.Contains(Feature.ConvertPitch))
        {
            var pitch = track.Pitch?.GenerateForDv(track.Notes);
            if (pitch is null)
            {
                segmentBytes.AddRange(SegmentDefaultParameterDataPitch);
            }
            else
            {
                AddListBlock(segmentBytes, pitch.Data.Select(p =>
                {
                    var entry = new List<byte>();
                    AddInt(entry, p.Tick);
                    AddInt(entry, p.Value);
                    return entry;
                }).ToList());
            }
        }
        else
        {
            segmentBytes.AddRange(SegmentDefaultParameterDataPitch);
        }

        segmentBytes.AddRange(SegmentDefaultParameterData2);

        var result = new List<byte>();
        AddInt(result, 0);
        AddString(result, track.Name);
        result.Add(0x00);
        result.Add(0x00);
        AddInt(result, DefaultVolume);
        AddInt(result, 0);
        AddListBlock(result, [segmentBytes]);
        return result;
    }

    private static List<byte> GenerateNote(Note note, List<FeatureConfig> features)
    {
        var result = new List<byte>();
        AddInt(result, (int)note.TickOn);
        AddInt(result, (int)note.Length);
        AddInt(result, ConvertNoteKeyInt(note.Key));
        AddInt(result, 0);
        AddString(result, note.Lyric);
        AddString(result, note.Lyric);
        result.Add(0x00);

        var vibratoBlock = new List<byte>();
        AddListBlock(vibratoBlock, [
            new List<byte>(CreateIntPair(-1, 0)),
            new List<byte>(CreateIntPair(100001, 0)),
        ]);
        AddListBlock(vibratoBlock, [
            new List<byte>(CreateIntPair(-1, 0)),
            new List<byte>(CreateIntPair(100001, 0)),
        ]);
        AddListBlock(vibratoBlock, [
            new List<byte>(CreateIntPair(0, 0)),
            new List<byte>(CreateIntPair(1124, 0)),
        ]);
        AddBlock(result, vibratoBlock);

        AddBlock(result, NoteUnknownDataBlock.ToList());
        result.AddRange(NoteUnknownPhonemes);

        if (features.Contains(Feature.ConvertPitch))
        {
            for (var i = 0; i < 4; i++) AddInt(result, 0);
        }
        else
        {
            AddInt(result, 8);
            AddInt(result, 5);
            AddInt(result, 16);
            AddInt(result, 16);
        }

        AddInt(result, -1);
        AddString(result, "");
        AddInt(result, -1);
        return result;
    }

    private static byte[] CreateIntPair(int a, int b)
    {
        var bytes = new byte[8];
        BitConverter.GetBytes(a).CopyTo(bytes, 0);
        BitConverter.GetBytes(b).CopyTo(bytes, 4);
        return bytes;
    }

    private static void AddInt(List<byte> list, int value)
    {
        var bytes = BitConverter.GetBytes(value);
        if (!BitConverter.IsLittleEndian)
            Array.Reverse(bytes);
        list.AddRange(bytes);
    }

    private static void AddString(List<byte> list, string value)
    {
        var bytes = Encoding.UTF8.GetBytes(value);
        AddInt(list, bytes.Length);
        list.AddRange(bytes);
    }

    private static void AddBlock(List<byte> list, List<byte> block)
    {
        AddInt(list, block.Count);
        list.AddRange(block);
    }

    private static void AddList(List<byte> list, List<List<byte>> items)
    {
        AddInt(list, items.Count);
        foreach (var item in items)
            list.AddRange(item);
    }

    private static void AddListBlock(List<byte> list, List<List<byte>> items)
    {
        var block = new List<byte>();
        AddInt(block, items.Count);
        foreach (var item in items)
            block.AddRange(item);
        AddBlock(list, block);
    }

